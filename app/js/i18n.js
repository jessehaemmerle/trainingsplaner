const DICTS = { de, en };
let lang = 'de';

export const LANGS = { de: 'Deutsch', en: 'English' };
export const detectLang = () => ((navigator.language || 'de').toLowerCase().startsWith('de') ? 'de' : 'en');
export const getLang = () => lang;
export function setLang(l) {
  lang = DICTS[l] ? l : 'de';
  if (typeof document !== 'undefined') document.documentElement.lang = lang;
}

/** Looks up "a.b.c"; function entries are called with the given arguments. */
export function t(path, ...args) {
  let node = DICTS[lang];
  for (const key of path.split('.')) node = node?.[key];
  if (node === undefined) return path;
  return typeof node === 'function' ? node(...args) : node;
}

const fmt = (opts) => new Intl.DateTimeFormat(lang === 'de' ? 'de-AT' : 'en-GB', opts);
export const fmtDate = (iso, opts = { weekday: 'long', day: 'numeric', month: 'long' }) => fmt(opts).format(asDate(iso));
export const fmtShort = (iso) => fmt({ day: 'numeric', month: 'short' }).format(asDate(iso));
export const fmtLong = (iso) => fmt({ day: 'numeric', month: 'long', year: 'numeric' }).format(asDate(iso));
/** Weekday name for Monday-based index 0…6. */
export const dayName = (i, style = 'short') => fmt({ weekday: style }).format(new Date(2024, 0, 1 + i, 12));
